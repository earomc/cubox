//! The command line, which `main.rs` acts on.

use clap::{Arg, ArgAction, Command, crate_description, crate_name, crate_version, value_parser};
use cubox::{
    seed::parse_seed,
    seedfind::spec::{MAX_BLOCKS, position},
    tile_renderer::MAX_LEVEL,
};

/// The longest side of `img`, in pixels. Its 3 bytes per pixel come to about 3.2 GiB, and the tiles need that again.
pub(crate) const MAX_IMAGE_SIDE: u64 = 32768;

const SEED_HELP: &str = "Seed like in Minecraft: a number (negative too) or any text";

fn parse_seed_arg(text: &str) -> Result<i64, String> {
    parse_seed(text).ok_or_else(|| "the seed can't be blank".to_owned())
}

pub(crate) fn build_cmd() -> Command {
    Command::new(crate_name!())
        .about(crate_description!())
        .after_help("Without a subcommand the GUI opens.")
        .version(crate_version!())
        .subcommand(
            Command::new("gui").about("Launch the GUI")
                .arg(Arg::new("seed")
                    .help(SEED_HELP)
                    .value_parser(parse_seed_arg)
                    .allow_hyphen_values(true)
                    .default_value("0")
                )
                .arg(Arg::new("dimension")
                    .long("dimension")
                    .short('d')
                    .help("Dimension to show")
                    .value_parser(["overworld", "nether", "end"])
                    .default_value("overworld")
                )
                .arg(Arg::new("script")
                    .long("script")
                    .help("Run a script that moves the view and takes screenshots, see src/gui/script.rs")
                    .value_parser(value_parser!(std::path::PathBuf))
                )
        )
        .subcommand(
            Command::new("img").about("Create a map image")
                .arg(Arg::new("seed")
                    .help(SEED_HELP)
                    .value_parser(parse_seed_arg)
                    .allow_hyphen_values(true)
                    .required(true)
                )
                .arg(Arg::new("tile-size")
                    .help("Size of tile in pixels")
                    .long("tile-size")
                    .value_parser(value_parser!(u32).range(1..=MAX_IMAGE_SIDE as i64))
                    .default_value("128")
                )
                .arg(Arg::new("tiles")
                    .help("Amount of tiles per side")
                    .long("tiles")
                    .value_parser(value_parser!(i32).range(1..=MAX_IMAGE_SIDE as i64))
                    .default_value("1")
                )
                .arg(Arg::new("sample-height")
                    .help("Height / y-level at which to sample the biomes at. If you sample lower you will see cave biomes")
                    .long("sample-height")
                    .short('y')
                    .allow_negative_numbers(true)
                    .value_parser(value_parser!(i32))
                    .default_value("256")
                )
                .arg(Arg::new("level")
                    .long("level")
                    .help("Level of the map, as in the viewer, in powers of two. 0 means each pixel represents one quart (4x4 blocks), 1 -> 8x8 blocks per pixel, 2 -> 16x16 blocks per pixel etc.")
                    .value_parser(value_parser!(u8).range(0..=MAX_LEVEL as i64))
                    .default_value("0")
                )
                .arg(Arg::new("samples")
                    .long("samples")
                    .help("Samples per axis per pixel. The samples are averaged, so zoomed out maps blend biomes instead of aliasing. Cost grows with samples^2")
                    .value_parser(value_parser!(u8).range(1..=16))
                    .default_value("1")
                )
                .arg(Arg::new("dimension")
                    .long("dimension")
                    .short('d')
                    .help("Dimension to show")
                    .value_parser(["overworld", "nether", "end"])
                    .default_value("overworld")
                )
                .arg(Arg::new("exact")
                    .long("exact")
                    .help("Show the sampled pixel averages as they are. Zoomed far out they are mostly sampling noise, by default they are shaded to vary as much as the real area averages do")
                    .action(ArgAction::SetTrue)
                )
        )
        .subcommand(
            search_args(Command::new("seeds").about("Find seeds with what you ask for, see docs/seed-search.md"), "What to look for, one condition per line. See docs/seed-search.md")
                .arg(Arg::new("limit")
                    .long("limit")
                    .help("Stop after this many matches")
                    .value_parser(value_parser!(u64).range(1..))
                    .default_value("10")
                    .conflicts_with("tested")
                )
                .arg(Arg::new("tested")
                    .long("tested")
                    .help("Stop after covering this many seeds and show the best matches")
                    .value_parser(value_parser!(u64).range(1..))
                )
                .arg(Arg::new("top")
                    .long("top")
                    .help("How many of the best matches --tested shows")
                    .value_parser(value_parser!(usize))
                    .default_value("10")
                )
                .arg(Arg::new("from")
                    .long("from")
                    .help("Count up from this seed instead of trying random ones")
                    .allow_negative_numbers(true)
                    .value_parser(value_parser!(i64))
                    .conflicts_with("seeds")
                )
                .arg(Arg::new("seeds")
                    .long("seeds")
                    .help("Try the seeds in this file, one per line, numbers or text")
                    .value_parser(value_parser!(std::path::PathBuf))
                )
        )
        .subcommand(
            search_args(
                Command::new("locations")
                    .about("Find places in one seed, each result being one of what the first line asks for, see docs/seed-search.md")
                    .arg(Arg::new("seed")
                        .help(SEED_HELP)
                        .value_parser(parse_seed_arg)
                        .allow_hyphen_values(true)
                        .required(true)
                    ),
                "What to find on the first line, conditions around it on the others. See docs/seed-search.md",
            )
                .arg(Arg::new("within")
                    .long("within")
                    .help("How far the area to search reaches, in blocks")
                    .value_parser(value_parser!(i32).range(1..=MAX_BLOCKS as i64))
                    .default_value("10000")
                )
                .arg(Arg::new("of")
                    .long("of")
                    .help("The middle of the area to search, x,z")
                    .allow_hyphen_values(true)
                    .value_parser(position)
                    .default_value("0,0")
                )
                .arg(Arg::new("limit")
                    .long("limit")
                    .help("Stop after this many results, by default all of the area")
                    .value_parser(value_parser!(u64).range(1..))
                )
        )
}

/// What both searches take.
fn search_args(command: Command, conditions_help: &'static str) -> Command {
    command
        .arg(Arg::new("conditions")
            .help(conditions_help)
            .required_unless_present("file")
            .conflicts_with("file")
        )
        .arg(Arg::new("file")
            .long("file")
            .help("Read that from this file")
            .value_parser(value_parser!(std::path::PathBuf))
        )
        .arg(Arg::new("step")
            .long("step")
            .help("How far apart biomes and noises are looked at, in blocks. 4 is exact, a larger step is faster but can miss what is smaller than it")
            .value_parser(parse_step)
            .default_value("4")
        )
        .arg(Arg::new("threads")
            .long("threads")
            .help("Threads to use, all by default")
            .value_parser(clap::builder::RangedU64ValueParser::<usize>::new().range(1..))
        )
}

fn parse_step(text: &str) -> Result<i32, String> {
    text.parse()
        .ok()
        .filter(|step: &i32| *step >= 4 && *step % 4 == 0)
        .ok_or_else(|| "the step has to be a multiple of 4".to_owned())
}
